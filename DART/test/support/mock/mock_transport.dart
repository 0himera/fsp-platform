/// «Сеть» mock-режима: одна задержка на вызов.
///
/// ЗАЧЕМ ЗАДЕРЖКА, если данные уже в памяти: без неё экраны были бы
/// «мгновенными», и ветка «показали индикатор загрузки, потом данные» в демо
/// просто не проверялась бы — к продакшену она уезжается неотлаженной.
/// Число меньше реальной сети намеренно: демо не должно раздражать.
library;

Future<T> mockCall<T>(T Function() body) async {
  await Future<void>.delayed(const Duration(milliseconds: 120));
  return body();
}
