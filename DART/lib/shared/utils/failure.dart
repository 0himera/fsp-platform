/// Ошибка уровня сервиса (сеть, «не найдено», «уже зарегистрирован»).
///
/// ПОЧЕМУ СВОЙ КЛАСС, А НЕ StateError/Exception: контроллеры ловят ошибки
/// конструкцией `on Exception catch`. `StateError` — это `Error`, а не
/// `Exception`, и он пролетает мимо catch, роняя приложение. Собственный
/// тип, реализующий `Exception`, гарантирует: любая отказная ветка реального API
/// (и её тестовой подмены) превращается в текст в поле `error`, а не в красный
/// экран.
library;

class ServiceFailure implements Exception {
  const ServiceFailure(this.message);

  /// Готовое для пользователя описание («Приём заявок закрыт»).
  final String message;

  @override
  String toString() => message;
}

/// Текст ошибки для поля `error` в контроллере.
/// Серверные сообщения уже написаны по-русски и адресованы человеку
/// («Неверная почта или пароль»), поэтому их показываем как есть. А вот у
/// постороннего исключения (баг в коде, таймаут из не-API места) готового текста
/// нет — его приходится сочинять здесь, иначе пользователь увидит молчащий
/// экран вместо подсказки.
String failureMessage(Object error) => error is ServiceFailure
    ? error.message
    : 'Не получилось выполнить действие. Попробуйте ещё раз.';
