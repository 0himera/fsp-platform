/// Длина текста в байтах UTF-8 — той же мерой, какой её мерит бэкенд.
///
/// ЗАЧЕМ ЭТО НУЖНО: Go считает длину строки через `len()`, то есть В БАЙТАХ,
/// а Dart через `String.length` — в кодюнитах UTF-16. Для латиницы числа
/// совпадают, для русской буквы расходятся вдвое: «аб» — это 2 символа для
/// клиента и 4 байта для сервера. Все лимиты в `validInput`, `register` и
/// `validateProtocol` проставлены в байтах, поэтому и наш проверяльщик обязан
/// мерить байтами — иначе форма пропустит значение, которое сервер отклонит с
/// бессмысленным «Проверьте данные соревнования и протокола».
///
/// Проверено на живом сервере: название из двух кириллиц (4 байта) он
/// ПРИНИМАЕТ, а `ab` из двух латинских букв (2 байта) — отклоняет; второй
/// случай как раз и закрепляет `test/live_api_test.dart`. Клиент обязан
/// отвечать так же, иначе он расходится с бэкендом в обе стороны: то не
/// пускает валидное, то отправляет то, что сервер завернёт.
library;

import 'dart:convert';

/// Число байт, которые строка [value] займёт в UTF-8.
///
/// Непарный суррогат (обрезанная эмодзи из буфера обмена) `utf8.encode`
/// превращает в `FormatException`, а валидатор формы не имеет права ронять
/// приложение: на битом вводе одинокие суррогаты считаются как `?`. Оценка для
/// такого ввода слегка занижена, но это ровно тот случай, где форма и так
/// бессильна — разбираться с ним должен тот, кто его вставил.
int utf8Length(String value) {
  try {
    return utf8.encode(value).length;
  } on FormatException {
    return utf8
        .encode(value.replaceAll(RegExp(r'[\uD800-\uDFFF]'), '?'))
        .length;
  }
}

/// Подсказка про верхнюю границу поля: сколько байт и почему это не «символы».
///
/// Пишем «байт» прямо в тексте: пользователь, вставивший 90 русских букв в поле
/// «до 100», иначе видит необъяснимый отказ.
String utf8LimitHint(String field, int bytes) =>
    '$field — не длиннее $bytes байт (русская буква занимает 2 байта)';
